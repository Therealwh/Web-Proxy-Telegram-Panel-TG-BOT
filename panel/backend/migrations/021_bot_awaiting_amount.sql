-- Состояние «бот ждёт свою сумму пополнения».
--
-- Раньше это был обычный Map в памяти процесса. Он полностью исчезал при
-- любом перезапуске панели: пользователь нажимал «Своя сумма», вводил
-- число — а бот молчал, потому что к этому моменту он уже не помнил,
-- что число от него ждут. Особенно часто это случалось сразу после
-- обновления панели.
--
-- Теперь ожидание хранится в базе и живёт ограниченное время, после
-- чего само собой снимается.

